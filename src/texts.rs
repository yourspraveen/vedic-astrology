//! Reading texts for the full report, in English, Tamil and Hindi. Written for this app from
//! the traditional meanings; nothing here is taken from another program's reports.

use crate::i18n::li;

pub fn weekday(w: usize) -> &'static str {
    WEEKDAY[li()][w % 7]
}
pub fn nakshatra(n: usize) -> &'static str {
    NAKSHATRA[li()][n % 27]
}
/// Tithi 0..29 (Amavasya = 29).
pub fn tithi(t: usize) -> &'static str {
    let i = if t == 29 { 15 } else { t % 15 };
    TITHI[li()][i]
}
pub fn karana(k: usize) -> &'static str {
    KARANA[li()][k % 11]
}
pub fn nithya_yoga(y: usize) -> &'static str {
    NITHYA[li()][y % 27]
}
pub fn lagna(s: usize) -> &'static str {
    LAGNA[li()][s % 12]
}
pub fn house_meaning(h: usize) -> &'static str {
    HOUSE[li()][(h + 11) % 12]
}
/// Dasha reading for a graha index (Sun = 0 … Ketu = 8).
pub fn dasha(g: usize) -> &'static str {
    DASHA[li()][g % 9]
}
pub fn tpl(key: Tpl) -> &'static str {
    TEMPLATES[key as usize][li()]
}

